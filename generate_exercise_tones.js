#!/usr/bin/env node
'use strict';

/*
  Local exercise tone generator
  -----------------------------
  Creates a lightweight piano-like WAV bank for MIDI 36..96 in assets/exercise/.
  Zero dependencies: only Node.js built-ins are used. No browser, npm install,
  Playwright, Firefox automation, ffmpeg, or network access is required.

  Run from the suite root:
      node generate_exercise_tones.js
*/

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const OUT = path.join(ROOT, 'assets', 'exercise');
const SAMPLE_RATE = 44100;
const DURATION = 1.35;
const MIDI_MIN = 36; // C2
const MIDI_MAX = 96; // C7
const AMPLITUDE = 0.72;

fs.mkdirSync(OUT, { recursive: true });

function frequency(midi) {
  return 440 * Math.pow(2, (midi - 69) / 12);
}

function writeString(buf, offset, text) {
  buf.write(text, offset, text.length, 'ascii');
}

function makeWav(midi) {
  const f = frequency(midi);
  const frames = Math.floor(SAMPLE_RATE * DURATION);
  const bytesPerSample = 2;
  const dataBytes = frames * bytesPerSample;
  const buf = Buffer.alloc(44 + dataBytes);

  writeString(buf, 0, 'RIFF');
  buf.writeUInt32LE(36 + dataBytes, 4);
  writeString(buf, 8, 'WAVE');
  writeString(buf, 12, 'fmt ');
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20);              // PCM
  buf.writeUInt16LE(1, 22);              // mono
  buf.writeUInt32LE(SAMPLE_RATE, 24);
  buf.writeUInt32LE(SAMPLE_RATE * bytesPerSample, 28);
  buf.writeUInt16LE(bytesPerSample, 32);
  buf.writeUInt16LE(16, 34);
  writeString(buf, 36, 'data');
  buf.writeUInt32LE(dataBytes, 40);

  // Piano-like struck tone: fast attack, multi-partial body, exponential decay,
  // tiny deterministic detune for width/realism, and a short hammer transient.
  const attack = 0.008;
  const tau = 0.46 + Math.max(0, (72 - midi)) * 0.003;
  const phase2 = 0.31, phase3 = 1.17, phase4 = 2.06;
  for (let i = 0; i < frames; i++) {
    const t = i / SAMPLE_RATE;
    const envAttack = Math.min(1, t / attack);
    const decay = Math.exp(-t / tau);
    const release = t > DURATION - 0.12 ? Math.max(0, (DURATION - t) / 0.12) : 1;
    const env = envAttack * decay * release;

    const fundamental = Math.sin(2 * Math.PI * f * t);
    const h2 = 0.31 * Math.sin(2 * Math.PI * f * 2.002 * t + phase2);
    const h3 = 0.15 * Math.sin(2 * Math.PI * f * 3.006 * t + phase3);
    const h4 = 0.07 * Math.sin(2 * Math.PI * f * 4.011 * t + phase4);
    const soft = 0.055 * Math.sin(2 * Math.PI * f * 0.501 * t + 0.6);
    const hammer = t < 0.03 ? (0.11 * (1 - t / 0.03) * Math.sin(2 * Math.PI * 1800 * t)) : 0;

    let sample = (fundamental + h2 + h3 + h4 + soft) / 1.585;
    sample = sample * env * AMPLITUDE + hammer;
    sample = Math.max(-1, Math.min(1, sample));
    buf.writeInt16LE(Math.round(sample * 32767), 44 + i * 2);
  }
  return buf;
}

const manifest = {};
let total = 0;
for (let midi = MIDI_MIN; midi <= MIDI_MAX; midi++) {
  const file = `midi-${midi}.wav`;
  const bytes = makeWav(midi);
  fs.writeFileSync(path.join(OUT, file), bytes);
  manifest[String(midi)] = `assets/exercise/${file}`;
  total += bytes.length;
  process.stdout.write(`\rGenerated MIDI ${midi}/${MIDI_MAX}`);
}
process.stdout.write('\n');

const manifestJs = `// Generated by generate_exercise_tones.js\nwindow.EXERCISE_TONES = ${JSON.stringify(manifest, null, 2)};\n`;
fs.writeFileSync(path.join(OUT, 'tone_manifest.js'), manifestJs, 'utf8');
fs.writeFileSync(path.join(OUT, 'tone_manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');

console.log(`Created ${Object.keys(manifest).length} local tones in ${OUT}`);
console.log(`Audio bytes: ${(total / 1024 / 1024).toFixed(2)} MiB`);
console.log('No external packages were installed.');
